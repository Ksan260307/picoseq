"""UI の調整用の定数だけを集めた小さなモジュール。

app / dj_control / selftest が共有する。どこにも依存しないので循環 import を起こさない。
"""

LIVE_DEBOUNCE_MS = 140      # 演奏中の編集をまとめて再レンダリングする間隔
DJ_RENDER_DEBOUNCE_MS = 120  # DJ: 次ループの事前レンダリングをまとめる間隔
DJ_ADVANCE_LOOPS = 4        # DJ: 何ループ流したら自動で次へ進むか (2小節×4 = 8小節)
DJ_SCRATCH_MS = 45          # スクラッチ音の最短間隔 (ミリ秒)
DJ_HISTORY_COMMIT_MS = 800  # つまみ操作を履歴へ確定するまでの待ち (デバウンス)
DJ_FLOW_CANDIDATES = 4      # DJ: 次フレーズのシード候補数 (音数の近いものを選ぶ)
SURPRISE_BPM = (80, 180)    # サプライズのテンポの振れ幅 (極端に速い/遅いを避ける)

# サプライズの拍子。4/4 を厚めにした重み付き抽選 (毎回 7/4 だと聴き疲れる)。
SURPRISE_BEATS = (2, 3, 3, 4, 4, 4, 4, 5, 6, 7)

# 曲調の性格グループごとのテンポ。全域から一様に振ると
# 「ボス戦が 80 BPM」「幻想が 180 BPM」になり、演奏の型だけ曲調に寄せても台無しになる。
# キーは core.music の FAMILY_* の値 (ここを依存させないため文字列で持つ。
# 取りこぼしは test_tuning の網羅テストが検出する)。
MOOD_BPM = {
    "bright": (110, 150),   # 明るい・ポップ
    "open": (85, 115),      # のどか・開放
    "lyric": (80, 110),     # 切ない・叙情
    "sorrow": (80, 105),    # 哀愁・緊張
    "exotic": (95, 135),    # エキゾチック
    "blues": (85, 120),     # ブルース
    "jazz": (110, 160),     # ジャズ
    "dream": (80, 105),     # 幻想・浮遊
    "folk5": (80, 110),     # 五音・民族 (和/都節)
    "sunny5": (105, 145),   # 五音・陽 (ペンタ/琉球)
    "fierce": (150, 180),   # 激しい
}


def surprise_bpm(family: str) -> tuple:
    """曲調の性格グループに合ったテンポの範囲。未知のグループは全域。"""
    return MOOD_BPM.get(family, SURPRISE_BPM)
